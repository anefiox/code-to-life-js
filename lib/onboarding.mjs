// A Markdown onboarding guide built from everything Code to Life knows about
// the project, for the team to read or commit.
import fs from 'node:fs';
import path from 'node:path';
import { explanationsFor, projectGlossary } from './explain.mjs';
import { folderGroups, folderNote } from './folders.mjs';
import { routeFlows, startTour } from './learn.mjs';
import { recipes } from './recipes.mjs';
import { settingsMap } from './settings.mjs';
import { hotspots } from './history.mjs';

const cell = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const code = text => '`' + String(text).replace(/`/g, '\'') + '`';

export function onboardingGuide(root, graph, { date = new Date() } = {}) {
  let pkg = {};
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  } catch {
    // Not a package: the guide just has fewer sections.
  }
  const name = pkg.name ?? path.basename(root);
  const explanations = explanationsFor(root, graph);
  const byId = new Map(graph.nodes.map(node => [node.id, node]));
  const out = ['# Getting started with ' + name, '',
    '_Generated by Code to Life on ' + date.toISOString().slice(0, 10) + '. Regenerate it after big changes._', ''];
  if (pkg.description) out.push(pkg.description, '');
  const tools = projectGlossary(root);
  if (tools.length) {
    out.push('## Tools it is built with', '');
    for (const tool of tools) out.push('- **' + tool.term + '** (' + code(tool.package) + '): ' + tool.meaning);
    out.push('');
  }
  const all = recipes(root, graph);
  const run = all.find(recipe => recipe.id === 'run');
  if (run) {
    out.push('## Run it', '');
    for (const step of run.steps) out.push('- ' + step.text);
    out.push('');
  }
  const { groups } = folderGroups(graph);
  out.push('## How the code is organised', '');
  for (const group of [...groups.values()].sort((a, b) => a.dir.localeCompare(b.dir))) {
    const note = folderNote(group.dir);
    out.push('- ' + code((group.dir || '(project root)') + '/') + ' · ' + group.files.length + ' file' +
      (group.files.length === 1 ? '' : 's') + (note ? ': ' + note : ''));
  }
  out.push('');
  const tour = startTour(root, graph).steps;
  if (tour.length) {
    out.push('## Start here', '', 'Read these files in order. Each one leads to the next.', '');
    tour.forEach((step, index) => {
      out.push((index + 1) + '. ' + code(step.file) + ': ' + step.reason);
      const summary = explanations[step.id]?.summary;
      if (summary) out.push('   ', '   ' + summary);
    });
    out.push('');
  }
  const pages = routeFlows(root, graph);
  if (pages.routes.length) {
    out.push('## Pages', '', '| Method | Address | Handled by | Template |', '| --- | --- | --- | --- |');
    for (const route of pages.routes) {
      const handler = byId.get(route.handler);
      out.push('| ' + cell(route.method) + ' | ' + cell(route.path) + ' | ' +
        cell(handler ? handler.name + ' (' + handler.file + ')' : route.file) + ' | ' +
        cell(route.templates.map(item => item.file ?? item.name).join(', ')) + ' |');
    }
    out.push('');
    if (pages.before) out.push(pages.before, '');
  }
  const { settings } = settingsMap(root, graph);
  if (settings.length) {
    out.push('## Settings', '', '| Setting | Environment variable | Default | What it is for |', '| --- | --- | --- | --- |');
    for (const setting of settings) {
      out.push('| ' + cell(setting.key) + ' | ' + cell(setting.env ?? '') + ' | ' +
        cell(setting.sensitive ? '(secret)' : setting.default) + ' | ' + cell(setting.doc) + ' |');
    }
    out.push('');
  }
  const howTo = all.filter(recipe => recipe.id !== 'run');
  if (howTo.length) {
    out.push('## How do I…', '');
    for (const recipe of howTo) {
      out.push('### ' + recipe.title, '', recipe.summary, '');
      recipe.steps.forEach((step, index) => out.push((index + 1) + '. ' + step.text + (step.file ? ' See ' + code(step.file + ':' + step.line) + '.' : '')));
      out.push('');
    }
  }
  const files = graph.nodes.filter(node => node.kind === 'module' && explanations[node.id])
    .sort((a, b) => a.file.localeCompare(b.file));
  if (files.length) {
    out.push('## Files explained', '');
    for (const node of files) out.push('- ' + code(node.file) + ': ' + explanations[node.id].summary.replace(/\s*\n\s*/g, ' '));
    out.push('');
  }
  const history = hotspots(root, graph);
  if (history.available && history.hotspots.length) {
    out.push('## Most changed files', '', 'Files that change often are where most work happens, and where a mistake is most likely.', '');
    for (const entry of history.hotspots.slice(0, 10)) {
      out.push('- ' + code(entry.file) + ': ' + entry.commits + ' commit' + (entry.commits === 1 ? '' : 's') + ', last on ' + entry.last);
    }
    out.push('');
  }
  return out.join('\n');
}
